import React, { useState } from 'react';
import {
  ArrowLeft,
  Copy,
  Check,
  Download,
  Printer,
  Sparkles,
  AlertTriangle,
  CheckCircle2,
  RotateCcw,
} from 'lucide-react';
import type { NoticeAnalysisResult } from '../types';

interface ResultsHeaderProps {
  result: NoticeAnalysisResult;
  currentLanguage: string;
  onLanguageChange: (lang: string) => void;
  onReset: () => void;
  onScrollToWorkspace: () => void;
}

export const ResultsHeader: React.FC<ResultsHeaderProps> = ({
  result,
  currentLanguage,
  onLanguageChange,
  onReset,
  onScrollToWorkspace,
}) => {
  const isHindi = currentLanguage === 'hi';
  const [copied, setCopied] = useState(false);

  const handleCopySummary = () => {
    const textToCopy = `SUCHNASETU AI ANALYSIS REPORT\nTitle: ${result.notice_title}\nDocument ID: ${result.document_id}\nLanguage: ${result.language.toUpperCase()}\n\nSUMMARY:\n${result.summary}\n\nGENERATED BY: ${result.model_used}`;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleExportJson = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(result, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', `suchnasetu_analysis_${result.document_id}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const handlePrint = () => {
    window.print();
  };

  const hasUncertainty = result.needs_user_confirmation;

  return (
    <div className="results-toolbar-card" id="results-dashboard">
      <div className="results-toolbar-main">
        {/* Document Title & Meta */}
        <div className="results-doc-meta">
          <div className="results-badge-row">
            <span className="results-kicker">
              {isHindi ? 'विश्लेषण परिणाम' : 'Analysis Results'}
            </span>
            <span className="doc-id-pill" title="Unique Session Document ID">
              ID: {result.document_id}
            </span>
            {hasUncertainty ? (
              <span className="status-badge-toolbar warning">
                <AlertTriangle size={13} />
                <span>{isHindi ? 'समीक्षा आवश्यक' : 'Needs Review'}</span>
              </span>
            ) : (
              <span className="status-badge-toolbar success">
                <CheckCircle2 size={13} />
                <span>{isHindi ? 'तथ्य सत्यापित' : 'Grounded & Ready'}</span>
              </span>
            )}
          </div>

          <h2 className="results-doc-title">{result.notice_title}</h2>

          <div className="results-source-info">
            <span className="source-meta-tag">
              {result.source_type === 'image'
                ? (isHindi ? 'स्रोत: ओसीआर छवि' : 'Source: RapidOCR Image')
                : (isHindi ? 'स्रोत: सीधा पाठ' : 'Source: Pasted Text')}
            </span>
            <span className="source-meta-tag model-meta-tag" title={result.model_used}>
              <Sparkles size={12} />
              <span>{result.model_used}</span>
            </span>
          </div>
        </div>

        {/* Action Controls */}
        <div className="results-toolbar-actions">
          {/* Language Quick Toggle */}
          <div className="toolbar-lang-toggle" role="group" aria-label="Output Language">
            <button
              type="button"
              className={`lang-pill ${currentLanguage === 'en' ? 'active' : ''}`}
              onClick={() => onLanguageChange('en')}
            >
              EN
            </button>
            <button
              type="button"
              className={`lang-pill ${currentLanguage === 'hi' ? 'active' : ''}`}
              onClick={() => onLanguageChange('hi')}
            >
              हिंदी
            </button>
          </div>

          {/* Copy Report */}
          <button
            type="button"
            className="btn btn-toolbar"
            onClick={handleCopySummary}
            title={isHindi ? 'सारांश रिपोर्ट कॉपी करें' : 'Copy summary report'}
          >
            {copied ? <Check size={14} className="text-emerald-600" /> : <Copy size={14} />}
            <span>{copied ? (isHindi ? 'कॉपी हुआ' : 'Copied') : (isHindi ? 'कॉपी' : 'Copy')}</span>
          </button>

          {/* Export JSON */}
          <button
            type="button"
            className="btn btn-toolbar"
            onClick={handleExportJson}
            title={isHindi ? 'पूर्ण विश्लेषण JSON डाउनलोड करें' : 'Download analysis JSON'}
          >
            <Download size={14} />
            <span>JSON</span>
          </button>

          {/* Print / Save PDF */}
          <button
            type="button"
            className="btn btn-toolbar hide-on-print"
            onClick={handlePrint}
            title={isHindi ? 'प्रिंट करें या पीडीएफ सहेजें' : 'Print or save report'}
          >
            <Printer size={14} />
            <span>{isHindi ? 'प्रिंट' : 'Print'}</span>
          </button>

          {/* Return to Notice Input */}
          <button
            type="button"
            className="btn btn-toolbar-secondary"
            onClick={onScrollToWorkspace}
            title={isHindi ? 'इनपुट क्षेत्र पर वापस जाएं' : 'Return to notice upload input'}
          >
            <ArrowLeft size={14} />
            <span>{isHindi ? 'इनपुट देखें' : 'View Input'}</span>
          </button>

          {/* New Analysis Reset */}
          <button
            type="button"
            className="btn btn-toolbar-primary"
            onClick={onReset}
            title={isHindi ? 'नया नोटिस जांचें' : 'Analyze another notice'}
          >
            <RotateCcw size={14} />
            <span>{isHindi ? 'नया नोटिस' : 'New Notice'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
