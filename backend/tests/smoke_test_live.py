import sys
import os
sys.path.insert(0, os.path.abspath("."))
import json
from fastapi.testclient import TestClient
from app.main import app

sys.stdout.reconfigure(encoding='utf-8')
client = TestClient(app)

print("=== STARTING REAL LIVE GEMMA 4 SMOKE TEST ===")

# 1. Health check
health_resp = client.get("/api/health")
health = health_resp.json()
print("1. Health Endpoint:")
print(f"   status: {health.get('status')}")
print(f"   model_provider: {health.get('model_provider')}")
print(f"   gemma_model: {health.get('gemma_model')}")
print(f"   live_inference_available: {health.get('live_inference_available')}")

# 2. Upload actual scholarship notice sample
print("\n2. Submitting actual scholarship image (RapidOCR + Live Gemma 4)...")
with open("../samples/scholarship_notice_2026.png", "rb") as f:
    resp = client.post(
        "/api/analyze",
        files={"file": ("scholarship_notice_2026.png", f, "image/png")},
        data={"language": "en", "reading_level": "standard"}
    )

print(f"   HTTP Status: {resp.status_code}")
assert resp.status_code == 200, f"Analysis failed: {resp.text}"

result = resp.json()
doc_id = result.get("document_id")
is_mock = result.get("is_mock_inference")
model_used = result.get("model_used")
ocr_conf = result.get("ocr_confidence")

print("\n3. Inference Provenance Verification:")
print(f"   document_id: {doc_id}")
print(f"   is_mock_inference: {is_mock}")
print(f"   model_used: {model_used}")
print(f"   ocr_confidence: {ocr_conf}")

assert is_mock is False, "Expected live inference, but is_mock_inference was True!"
assert "Live" in model_used, f"Expected Live in model_used, got: {model_used}"

# 4. Check all 6 structured fields
print("\n4. Six Mandatory PS 02 Fields (Live Gemma 4 Extraction):")
fields = result.get("fields", {})
for key in ["purpose", "eligibility", "deadline", "required_documents", "contact", "action"]:
    f_data = fields.get(key, {})
    val = f_data.get("value")
    status = f_data.get("status")
    ev_count = len(f_data.get("evidence", []))
    print(f"   - {key.upper()}: {val} [status: {status}, evidence count: {ev_count}]")
    assert status in ["found", "not_stated", "needs_confirmation"], f"Unexpected status: {status}"

# 5. Checklist verification
checklist = result.get("checklist", [])
print(f"\n5. Ordered Action Checklist ({len(checklist)} steps generated by Gemma 4):")
for step in checklist:
    print(f"   Step {step.get('step_number')}: {step.get('action')}")

# 6. Absent Requirement Grounded Q&A Verification
print("\n6. Grounded Q&A for Absent Requirement (Income Certificate / Cap):")
qa_resp = client.post(
    "/api/ask",
    json={
        "document_id": doc_id,
        "question": "Is an income certificate required or what is the parent income limit?",
        "language": "en"
    }
)
print(f"   QA Status Code: {qa_resp.status_code}")
assert qa_resp.status_code == 200, f"QA failed: {qa_resp.text}"

qa_data = qa_resp.json()
qa_stated = qa_data.get("is_stated_in_notice")
qa_answer = qa_data.get("answer")
qa_status = qa_data.get("status")

print(f"   is_stated_in_notice: {qa_stated}")
print(f"   status: {qa_status}")
print(f"   answer: {qa_answer}")

assert qa_stated is False, "Expected absent requirement to return is_stated_in_notice: False"

print("\n=== LIVE GEMMA 4 SMOKE TEST COMPLETED SUCCESSFULLY ===")
